import type { Connection } from '../connection';
import type { BookDepth } from '../types/symbol_price';

export type TradeSide = 'buy' | 'sell';
export type OrderType = 'ioc' | 'limit' | 'vwap' | 'barrier';
export type BarrierDirection = 'above' | 'below';
export type RestingOrder = {
  id: string;
  symbol: string;
  side: TradeSide;
  quantity: number;
  remaining_quantity: number;
  limit_price: number;
  timestamp: number;
  expires_at?: number;
  time_in_force?: 'gtc' | 'gtd';
  post_only?: boolean;
  maker_fee_rate: number;
  estimated_fee: number;
};
export type BarrierOrder = {
  id: string;
  symbol: string;
  side: TradeSide;
  quantity: number;
  remaining_quantity: number;
  filled_quantity: number;
  trigger_price: number;
  trigger_direction: BarrierDirection;
  order_kind?: 'barrier' | 'profit-target' | 'stop-market' | 'stop-limit' | 'trailing-stop';
  execution_type?: 'market' | 'limit';
  limit_price?: number;
  trailing_amount?: number;
  trailing_percent?: number;
  created_at: number;
  triggered_at?: number;
  status: string;
  average_execution_price?: number;
  error?: string;
};
export type OrdersResponse = { orders: RestingOrder[]; barrier_orders?: BarrierOrder[] };
export type VwapRun = {
  id: string;
  symbol: string;
  side: TradeSide;
  quantity: number;
  executed_quantity: number;
  duration_minutes: number;
  strategy?: 'vwap' | 'twap';
  started_at: number;
  status: string;
  market_vwap: number;
  execution_vwap: number;
  slippage: number;
  error?: string;
};
export type VwapRunsResponse = { runs: VwapRun[] };
export type OrderRow = {
  order: RestingOrder;
  current?: number;
  bookError?: string;
};
export type OrderManagerState = {
  symbols: string[];
  books: Record<string, BookDepth>;
  bookErrors: Record<string, string>;
  selectedSymbol: string;
  side: TradeSide;
  quantity: string;
  orderType: OrderType;
  limitPrice: string;
  barrierPrice: string;
  barrierDirection: BarrierDirection;
  orders: RestingOrder[];
  barrierOrders: BarrierOrder[];
  vwapRuns: VwapRun[];
  rows: OrderRow[];
  selectedCurrentPrice?: number;
  estimatedFee?: number;
  makerFeeRate: number;
  takerFeeRate: number;
  limitPriceWarning?: string;
  confirmedLimitPrice?: string;
  durationMinutes: string;
  participationRate: string;
  vwapRunId?: string;
  vwapStatus?: string;
  vwapExecutedQuantity?: number;
  loading: boolean;
  submitting: boolean;
  error?: string;
};
export type OrderManagerProps = { connection: Connection; symbols: string[] };
