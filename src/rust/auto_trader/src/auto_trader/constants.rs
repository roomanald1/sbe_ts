fn configured_taker_fee_rate() -> f64 {
    std::env::var("PAPER_OKX_SPOT_TAKER_FEE_RATE")
        .ok()
        .and_then(|value| value.parse::<f64>().ok())
        .filter(|value| value.is_finite() && *value >= 0.0 && *value <= 0.1)
        .unwrap_or(0.001)
}

